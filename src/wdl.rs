//! Win/draw/loss model and the display scale of the score.
//!
//! The search speaks in its own unit: the network's output multiplied by
//! [`crate::nnue::NETWORK_SCALE`], and 126 pruning margins in `tune.rs` are calibrated
//! against exactly that unit. It is not a unit anybody can read, though — the same
//! advantage prints here as a number two to three times what other engines show, because
//! they convert on the way out and we did not.
//!
//! This module is that conversion, and nothing else. It is read only where a score is
//! printed; the search never calls it, so nothing here can change how the engine plays.
//!
//! The model is the usual logistic one:
//!
//! ```text
//! P(win) = 1 / (1 + exp((a(m) - v) / b(m)))     v = internal score, side to move
//! m      = clamp(material, 17, 78) / 58         material = P + 3N + 3B + 5R + 9Q
//! cp     = round(100 * v / a(m))                +100 displayed = wins half its games
//! ```
//!
//! Note that this is a win *rate*, not an expected score: the engine draws about half its
//! games, so a position displayed at +100 scores nearer three quarters of a point.
//!
//! `a` and `b` are cubic in `m` because material changes what an advantage is worth. The
//! measured direction is the opposite of the intuitive one: a(78) = 231 in the opening
//! against a(20) = 304 in an endgame, so a given score converts *less* often once the
//! board empties — the drawn technically-better endgame is a real thing. `b` widens the
//! other way, 131 in the opening against 83 in an endgame: early on, the same score says
//! much less about the result.
//!
//! Fitted constants below are specific to one network and one playing regime — a
//! different champion converts differently, and pasting the wrong ones does not break
//! anything except the honesty of the number. See `vault/recherche/Normalisation du
//! score.md` for the measurement and its refresh procedure.

use crate::position::Position;
use crate::types::{Piece, is_mate_score, is_tb_score};

/// Lowest material count the fit covers; below it the model is frozen at this end.
pub const MATERIAL_MIN: i32 = 17;
/// Highest material count (16 pawns + 4 knights + 4 bishops + 4 rooks + 2 queens).
pub const MATERIAL_MAX: i32 = 78;
/// Material the fit is anchored at, so that `a(1.0)` is the pawn value.
pub const MATERIAL_ANCHOR: f64 = 58.0;

// ---- BEGIN fitted constants (generated by tools/scripts/wdl_model.py) ----
// Fitted 2026-10-19 on gaianet-t2b-t5: 10 000 games of the champion against itself at
// 80 000 fixed nodes, Hash 16, book UHO_4060_v4, raw scores; 950 988 scored positions
// over 62 material bins. Calibration on the same games: mean error 0.96 points of win
// rate, and 49.2 % wins at the +100 anchor against a target of 50 %.
//
// Refit whenever the champion changes:
//   python3 tools/scripts/wdl_model.py play --net nets/<champion>.bin
//   python3 tools/scripts/wdl_model.py fit var/wdl/<champion>.pgn
// and paste the printed block between these two markers.
//
/// `a(m) = AS[0]*m^3 + AS[1]*m^2 + AS[2]*m + AS[3]`, the internal score worth 50 % wins.
const AS: [f64; 4] = [-286.222, 812.049, -781.172, 503.312];
/// `b(m)`, the logistic width: how many internal centipawns separate 50 % from 73 %.
const BS: [f64; 4] = [-112.379, 343.388, -271.387, 137.817];
/// The internal score printed as `cp 100` at the anchor material, i.e. `round(a(1.0))`.
pub const NORMALIZE_TO_PAWN_VALUE: i32 = 248;
// ---- END fitted constants ----

/// The two coefficients of the logistic at one material count.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Params {
    /// Score at which the side to move expects to win half its games.
    pub a: f64,
    /// Width of the logistic, in the same unit.
    pub b: f64,
}

/// Pawns + 3 (knights + bishops) + 5 rooks + 9 queens, both colours.
///
/// Deliberately not [`Position::material`], which is SEE-weighted and drops pawns: this
/// is a count of what is left on the board, and the endgames the model cares about are
/// exactly the ones where pawns are all that is left.
pub fn material_count(pos: &Position) -> i32 {
    let count = |white: Piece, black: Piece| {
        (pos.pieces[white.index()] | pos.pieces[black.index()]).count_ones() as i32
    };
    let pawns = count(Piece::WHITE_PAWN, Piece::BLACK_PAWN);
    let knights = count(Piece::WHITE_KNIGHT, Piece::BLACK_KNIGHT);
    let bishops = count(Piece::WHITE_BISHOP, Piece::BLACK_BISHOP);
    let rooks = count(Piece::WHITE_ROOK, Piece::BLACK_ROOK);
    let queens = count(Piece::WHITE_QUEEN, Piece::BLACK_QUEEN);
    let material = pawns + 3 * (knights + bishops) + 5 * rooks + 9 * queens;
    debug_assert!(
        (0..=MATERIAL_MAX).contains(&material),
        "material_count: {material} outside 0..={MATERIAL_MAX}"
    );
    material
}

/// Evaluate both cubics at one material count.
///
/// The floor of 1.0 is a guard against a mistyped paste, not a modelling choice: a
/// non-positive `a` would flip the sign of every displayed score, and a non-positive `b`
/// would invert the win rate. A sound fit never comes near it.
fn params_for_material(material: i32) -> Params {
    let m = material.clamp(MATERIAL_MIN, MATERIAL_MAX) as f64 / MATERIAL_ANCHOR;
    let cubic = |c: [f64; 4]| ((c[0] * m + c[1]) * m + c[2]) * m + c[3];
    Params {
        a: cubic(AS).max(1.0),
        b: cubic(BS).max(1.0),
    }
}

/// The logistic coefficients for this position.
pub fn params(pos: &Position) -> Params {
    params_for_material(material_count(pos))
}

/// Probability in per mille that the side to move wins, given an internal score.
///
/// Safe at mate and tablebase magnitudes: the exponent saturates to zero or infinity and
/// the quotient stays finite either way.
pub fn win_permille(score: i32, pos: &Position) -> i32 {
    let Params { a, b } = params(pos);
    let permille = 1000.0 / (1.0 + ((a - f64::from(score)) / b).exp());
    permille.round() as i32
}

/// Convert an internal score to the displayed pawn-anchored scale.
///
/// Mate and tablebase scores never come here: they are printed as `mate N` or as the
/// conventional large centipawn value, on no scale at all.
pub fn to_cp(score: i32, pos: &Position) -> i32 {
    debug_assert!(
        !is_mate_score(score) && !is_tb_score(score),
        "to_cp: decisive score {score} has no place on the win-rate scale"
    );
    let Params { a, .. } = params(pos);
    (100.0 * f64::from(score) / a).round() as i32
}

/// Win, draw and loss probabilities in per mille, from the point of view of the side to
/// move. The three always sum to 1000.
pub fn wdl(score: i32, pos: &Position) -> (i32, i32, i32) {
    let win = win_permille(score, pos).clamp(0, 1000);
    let loss = win_permille(-score, pos).clamp(0, 1000);
    let draw = 1000 - win - loss;
    debug_assert!(draw >= 0, "wdl: win {win} + loss {loss} exceeds 1000");
    (win, draw, loss)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::position::Position;

    /// A position at exactly the anchor material (58): the full array minus both queens
    /// and both c-pawns (78 − 18 − 2).
    fn anchored() -> Position {
        let pos = Position::from_fen("rnb1kbnr/pp1ppppp/8/8/8/8/PP1PPPPP/RNB1KBNR w KQkq - 0 1")
            .expect("valid fen");
        assert_eq!(material_count(&pos), MATERIAL_ANCHOR as i32);
        pos
    }

    #[test]
    fn startpos_material_is_the_maximum() {
        let pos = Position::from_fen("rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP/RNBQKBNR w KQkq - 0 1")
            .expect("valid fen");
        assert_eq!(material_count(&pos), MATERIAL_MAX);
    }

    #[test]
    fn a_bare_king_ending_is_the_minimum_after_clamping() {
        let pos = Position::from_fen("8/8/4k3/8/8/4K3/8/8 w - - 0 1").expect("valid fen");
        assert_eq!(material_count(&pos), 0);
        assert_eq!(params(&pos), params_for_material(MATERIAL_MIN));
    }

    /// The whole point of the anchor: the pawn value *is* `a(1.0)`, so a score of
    /// `NORMALIZE_TO_PAWN_VALUE` prints as +100 and means an even game half the time.
    #[test]
    fn anchor_invariant_holds() {
        let sum = AS.iter().sum::<f64>().round() as i32;
        assert_eq!(
            NORMALIZE_TO_PAWN_VALUE, sum,
            "NORMALIZE_TO_PAWN_VALUE must be round(a(1.0)); constants pasted half-way?"
        );
        let pos = anchored();
        assert_eq!(to_cp(NORMALIZE_TO_PAWN_VALUE, &pos), 100);
        assert_eq!(win_permille(NORMALIZE_TO_PAWN_VALUE, &pos), 500);
    }

    #[test]
    fn the_scale_is_symmetric_and_the_three_outcomes_sum_to_one() {
        let pos = anchored();
        assert_eq!(to_cp(0, &pos), 0);
        for score in (-2000..=2000).step_by(37) {
            let (w, d, l) = wdl(score, &pos);
            assert_eq!(w + d + l, 1000, "score {score}");
            assert_eq!(wdl(-score, &pos), (l, d, w), "score {score}");
            assert_eq!(to_cp(-score, &pos), -to_cp(score, &pos), "score {score}");
        }
    }

    #[test]
    fn a_better_score_never_wins_less_often() {
        let pos = anchored();
        let mut previous = -1;
        for score in (-3000..=3000).step_by(50) {
            let win = win_permille(score, &pos);
            assert!(win >= previous, "win rate fell at score {score}");
            previous = win;
        }
    }

    /// Decisive magnitudes must saturate rather than produce NaN or a negative draw.
    #[test]
    fn decisive_magnitudes_saturate() {
        let pos = anchored();
        assert_eq!(wdl(31_000, &pos), (1000, 0, 0));
        assert_eq!(wdl(-31_000, &pos), (0, 0, 1000));
    }

    #[test]
    fn material_outside_the_fitted_range_is_frozen_at_its_end() {
        assert_eq!(params_for_material(1), params_for_material(MATERIAL_MIN));
        assert_eq!(params_for_material(200), params_for_material(MATERIAL_MAX));
    }

    /// Catches a mistyped or half-pasted constants block: a sound fit stays well clear of
    /// the floor in `params_for_material`.
    #[test]
    fn the_fitted_coefficients_stay_positive_over_the_whole_range() {
        for material in MATERIAL_MIN..=MATERIAL_MAX {
            let Params { a, b } = params_for_material(material);
            assert!(a > 1.0, "a({material}) = {a} hit the safety floor");
            assert!(b > 1.0, "b({material}) = {b} hit the safety floor");
        }
    }
}
